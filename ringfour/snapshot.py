"""A recorded robot: what onboarding captures, and what reads it back.

Spec 8.7 deferred this as *"recorded descriptions as CI fixtures —
recorded from a live robot or sim, never authored"*. That clause is the
whole discipline. A snapshot is not a hand-written description; it is what
the robot actually said, captured with everything derivable from it, and
stamped with the sha of the bytes it came from.

    robots/profiles/base101_arm.yaml        the profile
    robots/profiles/base101_arm/<sha>/      what the robot turned out to be
        description.urdf   verbatim, as served on /robot_description
        hulls.json         bounding volumes for <mesh> collisions
        reach.npz          the reachability map, tip positions only
        meta.json          sha, when, by which agent, what it saw

**Beside the profile, not in a cache directory** (Cristi, 2026-08-25).
A profile says how to talk to a robot; a snapshot says what that robot
turned out to BE. They are two halves of the same description and they
belong in one place, under version control, where a diff shows you that
the arm changed.

**Why capture rather than point at a file.** Both, really. Pointing at a
URDF in a profile is what spec 26.2 forbids, and for a good reason: on a
robot whose tool is swappable and whose description is generated by a
configurator, a path describes whichever arm was fitted when someone wrote
that line. Capturing has the same benefits — meshes resolve, work happens
offline, CI gets a real fixture, expensive things are computed once — and
none of the drift, because the sha makes staleness loud instead of
silent.

**The guard.** `Welcome.description_sha` is the live robot's. A snapshot
knows the sha it was taken from. Compare them on connect: equal means the
snapshot describes the robot in front of you; different means re-onboard,
and nothing should quietly use the stale one.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from .description import CollisionShape, RobotDescription

__all__ = ["ReachMap", "Snapshot", "default_root", "search_roots"]

FORMAT_VERSION = 1


# Where snapshots live, in preference order. A snapshot sits beside the
# profile it belongs to, so these are the places a profile directory is
# normally found from.
SEARCH = ("RINGFOUR_SNAPSHOTS",)


def search_roots(extra: "str | Path | None" = None) -> list[Path]:
    """Directories to look in for snapshots, best first."""
    roots: list[Path] = []
    if extra is not None:
        roots.append(Path(extra))
    for variable in SEARCH:
        value = os.environ.get(variable)
        if value:
            roots.extend(Path(part) for part in value.split(os.pathsep) if part)
    here = Path.cwd()
    for candidate in (here, *here.parents):
        # A profile lives in its own robot's repo, so the useful entry
        # is the bare "profiles" found by walking UP from the cwd — run
        # anything from inside robots/<robot>/ and it resolves. The other
        # two are the shared-pool and pre-2026-08-26 layouts, kept so an
        # older tree still resolves rather than silently finding nothing
        # and recomputing a reach map that already exists.
        for relative in ("profiles", "robots/profiles", "engine/profiles"):
            path = candidate / relative
            if path.is_dir():
                roots.append(path)
        if (candidate / ".git").exists():
            break                    # do not wander above the repo
    return list(dict.fromkeys(roots))


def default_root() -> Path:
    """Where a new snapshot is written when nowhere else is named."""
    found = search_roots()
    return found[0] if found else Path.cwd()


@dataclass(frozen=True)
class ReachMap:
    """Where the tip can be put, as a voxel grid in the base frame.

    Built by sampling JOINT space forward — draw a configuration within
    the limits, run FK, drop the tip into a voxel — rather than by asking
    IK about each voxel. The inverse direction is unaffordable: an
    unreachable pose costs the solver most of a second, and a grid has
    hundreds of thousands of them. Forward sampling costs one FK and one
    collision check per sample, and it gets joint limits and
    self-collision for free because it never generates a configuration
    that violates them.

    ``counts`` is how many samples landed in each voxel, which is more
    useful than a boolean: it says how many ways there are to get there.
    Low counts are places the arm can just barely scrape into.

    **It is a lower bound.** An empty voxel is probably unreachable, not
    provably — a pose reachable from one narrow sliver of joint space may
    simply not have been drawn. Treat `can_reach` as "yes" being reliable
    and "no" meaning "not seen in N samples".

    **Tip positions only** (Cristi, 2026-08-25). It answers "can the tip
    be here", not "can it be here pointing that way" — orientation
    coverage is a 6-D grid and a much larger computation. Deliberately
    left for later.
    """

    origin: tuple[float, float, float]     # centre of voxel (0, 0, 0)
    resolution: float                      # metres per voxel
    counts: np.ndarray                     # uint32, shape (nx, ny, nz)
    samples: int                           # configurations drawn
    rejected: int                          # discarded for self-collision

    @property
    def reachable_voxels(self) -> int:
        return int(np.count_nonzero(self.counts))

    def index_of(self, point: tuple[float, float, float]
                 ) -> tuple[int, int, int] | None:
        """Voxel containing ``point``, or None if outside the grid."""
        idx = tuple(
            int(round((p - o) / self.resolution))
            for p, o in zip(point, self.origin)
        )
        if any(i < 0 or i >= n for i, n in zip(idx, self.counts.shape)):
            return None
        return idx  # type: ignore[return-value]

    def can_reach(self, point: tuple[float, float, float]) -> bool:
        """True if any sample put the tip in this voxel. A lookup, not a
        solve — which is the point of precomputing it."""
        idx = self.index_of(point)
        return idx is not None and bool(self.counts[idx])

    def density(self, point: tuple[float, float, float]) -> float:
        """Samples in this voxel over the busiest voxel, 0..1.

        The dexterity signal: 1.0 is the sweet spot, near 0 is a place the
        arm can only just get to.
        """
        idx = self.index_of(point)
        if idx is None:
            return 0.0
        peak = int(self.counts.max()) or 1
        return float(self.counts[idx]) / peak

    def occupied(self) -> tuple[np.ndarray, np.ndarray]:
        """(points, counts) for every non-empty voxel — what a 3-D view
        wants, without shipping the empty 95% of the grid."""
        where = np.argwhere(self.counts > 0)
        points = where * self.resolution + np.asarray(self.origin)
        return points, self.counts[tuple(where.T)]


@dataclass(frozen=True)
class Snapshot:
    """A robot as recorded at one moment, keyed by its description sha."""

    robot: str
    sha: str
    description: RobotDescription
    # link -> the volumes onboarding worked out for its <mesh> collisions,
    # in the same shape as any other CollisionShape so the collision model
    # cannot tell the difference.
    hulls: dict[str, tuple[CollisionShape, ...]]
    reach: ReachMap | None
    meta: dict[str, Any]
    path: Path | None = None

    # -- reading --------------------------------------------------------------

    @classmethod
    def load(cls, directory: str | Path) -> "Snapshot":
        directory = Path(directory)
        meta = json.loads((directory / "meta.json").read_text())
        if meta.get("format") != FORMAT_VERSION:
            raise ValueError(
                f"{directory} is format {meta.get('format')}, this build "
                f"reads {FORMAT_VERSION}. Re-run onboarding.")
        urdf = (directory / "description.urdf").read_text()
        description = RobotDescription.parse(urdf)
        if description.sha != meta["sha"]:
            raise ValueError(
                f"{directory} is corrupt: description.urdf hashes to "
                f"{description.sha[:12]} but meta.json says "
                f"{meta['sha'][:12]}")
        hulls = _hulls_from(json.loads((directory / "hulls.json").read_text()))
        reach = None
        grid = directory / "reach.npz"
        if grid.exists():
            with np.load(grid) as data:
                reach = ReachMap(
                    origin=tuple(float(v) for v in data["origin"]),
                    resolution=float(data["resolution"]),
                    counts=data["counts"],
                    samples=int(data["samples"]),
                    rejected=int(data["rejected"]),
                )
        return cls(robot=meta["robot"], sha=meta["sha"],
                   description=description, hulls=hulls, reach=reach,
                   meta=meta, path=directory)

    @classmethod
    def find(cls, sha: str, root: str | Path | None = None
             ) -> "Snapshot | None":
        """The snapshot for this exact description, wherever it lives.

        Keyed by SHA and nothing else. Not by robot name: two profiles can
        name the same robot, a name can be edited, and neither changes
        what the robot is. The sha does — which is the point. A snapshot
        of a different build silently used in place of this one is the
        failure the whole scheme exists to prevent.
        """
        for base in search_roots(root):
            for directory in sorted(base.glob(f"*/{sha}")):
                if (directory / "meta.json").exists():
                    try:
                        return cls.load(directory)
                    except (ValueError, OSError):
                        continue
        return None

    def matches(self, live_sha: str | None) -> bool:
        """True if this snapshot describes the robot now on the wire."""
        return live_sha is not None and live_sha == self.sha

    @property
    def collisions(self) -> dict[str, tuple[CollisionShape, ...]]:
        """The description's collision shapes with meshes filled in.

        This is what makes the gripper visible: `<mesh>` entries carry no
        extent when parsed from XML, and here they are replaced by the
        boxes onboarding measured off the files.
        """
        merged: dict[str, tuple[CollisionShape, ...]] = {}
        for link, shapes in self.description.collisions.items():
            resolved = self.hulls.get(link)
            if resolved is None:
                merged[link] = shapes
                continue
            keep = tuple(s for s in shapes if s.modelled)
            merged[link] = keep + resolved
        return merged

    # -- writing --------------------------------------------------------------

    def write(self, directory: str | Path) -> Path:
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "description.urdf").write_text(self.description.urdf)
        (directory / "hulls.json").write_text(
            json.dumps(_hulls_to(self.hulls), indent=2))
        if self.reach is not None:
            np.savez_compressed(
                directory / "reach.npz",
                origin=np.asarray(self.reach.origin),
                resolution=self.reach.resolution,
                counts=self.reach.counts,
                samples=self.reach.samples,
                rejected=self.reach.rejected,
            )
        meta = dict(self.meta)
        meta.update({"format": FORMAT_VERSION, "robot": self.robot,
                     "sha": self.sha})
        (directory / "meta.json").write_text(json.dumps(meta, indent=2))
        return directory


def _hulls_to(hulls: dict[str, tuple[CollisionShape, ...]]) -> dict:
    return {
        link: [
            {"half": list(s.half), "origin_xyz": list(s.origin_xyz),
             "origin_rpy": list(s.origin_rpy), "mesh": s.mesh}
            for s in shapes
        ]
        for link, shapes in hulls.items()
    }


def _hulls_from(raw: dict) -> dict[str, tuple[CollisionShape, ...]]:
    return {
        link: tuple(
            CollisionShape(
                link=link, kind="box",
                half=tuple(entry["half"]),
                origin_xyz=tuple(entry["origin_xyz"]),
                origin_rpy=tuple(entry["origin_rpy"]),
                # mesh= is deliberately NOT set: once measured, the volume
                # is as good as a <box> and must count as modelled, or the
                # collision model would keep reporting it as invisible.
            )
            for entry in entries
        )
        for link, entries in raw.items()
    }
